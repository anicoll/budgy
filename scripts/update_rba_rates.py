"""Refresh the RBA average home loan rates in the engine.

Downloads Table F6 (Housing Lending Rates) as the Excel workbook, which has
rates to two decimal places (the CSV rounds them to one), and rewrites the
snapshot in packages/engine/src/mortgage/rbaRates.ts. Each rate line there
ends with a comment naming its new and outstanding series IDs, so this script
only touches numbers it can match to a series.

It also rewrites packages/engine/src/mortgage/rbaHistory.ts: the last 72
months of every series listed in rbaRates.ts, for the rate check chart.

Usage: python3 scripts/update_rba_rates.py [path/to/f06hist.xlsx]
       python3 scripts/update_rba_rates.py --csv path/to/f6-data.csv
With no path it downloads the workbook from the RBA. The CSV has rates
rounded to one decimal place, so --csv only rebuilds the history and leaves
the latest-month snapshot alone. Standard library only.
"""

import csv
import datetime as dt
import pathlib
import re
import sys
import urllib.request
import zipfile
from io import BytesIO
from xml.etree import ElementTree as ET

URL = "https://www.rba.gov.au/statistics/tables/xls/f06hist.xlsx"
ENGINE = pathlib.Path(__file__).resolve().parent.parent / "packages/engine/src/mortgage"
TARGET = ENGINE / "rbaRates.ts"
HISTORY_TARGET = ENGINE / "rbaHistory.ts"
HISTORY_MONTHS = 72
NS = {"m": "http://schemas.openxmlformats.org/spreadsheetml/2006/main"}


def load(path: str | None) -> bytes:
    if path:
        return pathlib.Path(path).read_bytes()
    req = urllib.request.Request(URL, headers={"User-Agent": "budgy rate update (GitHub Actions)"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read()


def read_sheet(data: bytes) -> list[dict[str, str]]:
    """The Data sheet as rows of {column letter: value}."""
    z = zipfile.ZipFile(BytesIO(data))
    strings = [
        "".join(t.text or "" for t in si.iter(f"{{{NS['m']}}}t"))
        for si in ET.fromstring(z.read("xl/sharedStrings.xml")).findall("m:si", NS)
    ]
    sheet = ET.fromstring(z.read("xl/worksheets/sheet1.xml"))
    rows = []
    for row in sheet.iter(f"{{{NS['m']}}}row"):
        cells = {}
        for c in row.findall("m:c", NS):
            v = c.find("m:v", NS)
            if v is None or v.text is None:
                continue
            col = re.match(r"[A-Z]+", c.get("r", "")).group(0)
            cells[col] = strings[int(v.text)] if c.get("t") == "s" else v.text
        if cells:
            rows.append(cells)
    return rows


def read_csv(path: str) -> list[dict[str, str]]:
    """The F6 CSV in the same shape as read_sheet (dates become Excel serials)."""
    rows = []
    with open(path, encoding="utf-8-sig", newline="") as f:
        for line in csv.reader(f):
            cells = {}
            for i, v in enumerate(line):
                if v == "":
                    continue
                col = chr(65 + i) if i < 26 else chr(64 + i // 26) + chr(65 + i % 26)
                cells[col] = v
            first = cells.get("A", "")
            if re.fullmatch(r"\d{1,2}/\d{1,2}/\d{4}", first):
                d = dt.datetime.strptime(first, "%d/%m/%Y").date()
                cells["A"] = str((d - dt.date(1899, 12, 30)).days)
            if cells:
                rows.append(cells)
    return rows


def excel_date(serial: str) -> dt.date:
    return dt.date(1899, 12, 30) + dt.timedelta(days=int(float(serial)))


def parse_published(text: str) -> dt.date:
    for fmt in ("%d-%b-%Y", "%d/%m/%Y", "%Y-%m-%d"):
        try:
            return dt.datetime.strptime(text.strip(), fmt).date()
        except ValueError:
            pass
    return excel_date(text)


def render_history(source: str, column: dict[str, str], data_rows: list[dict[str, str]]) -> str:
    """The TypeScript for the monthly history of every series in rbaRates.ts."""
    key_re = re.compile(
        r'^\s+("?[a-z0-9-]+"?): \{ new: [0-9.]+, outstanding: [0-9.]+ \}, // ([A-Z0-9]+), ([A-Z0-9]+)',
        re.M,
    )
    purposes = re.findall(r'^    ("?[a-z0-9-]+"?): \{$', source, re.M)
    pairs = key_re.findall(source)
    per = len(pairs) // len(purposes)
    window = data_rows[-HISTORY_MONTHS:]
    first = excel_date(window[0]["A"]).strftime("%Y-%m")

    def series(sid: str) -> str:
        values = []
        for r in window:
            v = round(float(r[column[sid]]) / 100, 6)
            if not 0.01 < v < 0.2:
                raise ValueError(f"{sid} = {v} looks wrong")
            values.append(repr(v))
        return "[" + ", ".join(values) + "]"

    out = [
        "/**",
        " * Monthly history of the average home loan rates in rbaRates.ts, from the same",
        " * RBA Table F6 series, oldest month first. Generated by scripts/update_rba_rates.py;",
        " * do not edit by hand.",
        " */",
        "",
        'import type { LoanPurpose, RateSeries } from "./rbaRates";',
        "",
        "export interface RateHistory {",
        "  /** Average rate on new loans funded in each month. */",
        "  new: number[];",
        "  /** Average rate on all outstanding loans at the end of each month. */",
        "  outstanding: number[];",
        "}",
        "",
        "export interface RbaHousingHistory {",
        "  /** The first month in every series, YYYY-MM. */",
        "  first: string;",
        "  rates: Record<LoanPurpose, Record<RateSeries, RateHistory>>;",
        "}",
        "",
        "export const RBA_HOUSING_HISTORY: RbaHousingHistory = {",
        f'  first: "{first}",',
        "  rates: {",
    ]
    for pi, purpose in enumerate(purposes):
        out.append(f"    {purpose}: {{")
        for key, new_id, out_id in pairs[pi * per : (pi + 1) * per]:
            out.append(f"      {key}: {{")
            out.append(f"        new: {series(new_id)}, // {new_id}")
            out.append(f"        outstanding: {series(out_id)}, // {out_id}")
            out.append("      },")
        out.append("    },")
    out += ["  },", "};", ""]
    return "\n".join(out)


def main() -> int:
    args = sys.argv[1:]
    use_csv = "--csv" in args
    if use_csv:
        args.remove("--csv")
        if not args:
            print("--csv needs a path", file=sys.stderr)
            return 1
    path = args[0] if args else None
    rows = read_csv(path) if use_csv else read_sheet(load(path))
    ids = next(r for r in rows if r.get("A") == "Series ID")
    column = {v: k for k, v in ids.items() if k != "A"}
    published_row = next(r for r in rows if r.get("A") == "Publication date")

    source = TARGET.read_text()
    line_re = re.compile(
        r"(\{ new: )([0-9.]+)(, outstanding: )([0-9.]+)( \}, // )([A-Z0-9]+), ([A-Z0-9]+)"
    )
    wanted = [(m.group(6), m.group(7)) for m in line_re.finditer(source)]
    if not wanted:
        print("no series lines found in", TARGET, file=sys.stderr)
        return 1
    needed = {s for pair in wanted for s in pair}
    missing = needed - column.keys()
    if missing:
        print("series missing from F6:", ", ".join(sorted(missing)), file=sys.stderr)
        return 1

    data_rows = [
        r for r in rows if re.fullmatch(r"\d+(\.0)?", r.get("A", "")) and all(column[s] in r for s in needed)
    ]
    if len(data_rows) < HISTORY_MONTHS:
        print(f"only {len(data_rows)} months in the file; need {HISTORY_MONTHS}", file=sys.stderr)
        return 1
    history = render_history(source, column, data_rows)
    if not HISTORY_TARGET.exists() or HISTORY_TARGET.read_text() != history:
        HISTORY_TARGET.write_text(history)
        print(f"history rebuilt to {excel_date(data_rows[-1]['A']).strftime('%Y-%m')}")
    if use_csv:
        return 0
    latest = data_rows[-1]
    month = excel_date(latest["A"]).strftime("%Y-%m")
    published = parse_published(published_row[column[wanted[0][0]]]).isoformat()

    def rate(series: str) -> str:
        # Percent to a decimal with no float noise: 6.15 -> 0.0615.
        value = round(float(latest[column[series]]) / 100, 6)
        if not 0.01 < value < 0.2:
            raise ValueError(f"{series} = {value} looks wrong")
        return repr(value)

    def replace(m: re.Match) -> str:
        return f"{m.group(1)}{rate(m.group(6))}{m.group(3)}{rate(m.group(7))}{m.group(5)}{m.group(6)}, {m.group(7)}"

    updated = line_re.sub(replace, source)
    updated = re.sub(r'(  month: ")[0-9-]+(",)', rf"\g<1>{month}\2", updated, count=1)
    updated = re.sub(r'(  published: ")[0-9-]+(",)', rf"\g<1>{published}\2", updated, count=1)

    if updated == source:
        print(f"already up to date ({month})")
    else:
        TARGET.write_text(updated)
        print(f"updated to {month}, published {published}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
