// Generates src/app/m3-tokens.css: the Material 3 colour roles for budgy's
// Harbour palette, in light and dark, from two seed colours. Run it after
// changing a seed: `pnpm --filter @budgy/web colors`.
import { writeFileSync } from "node:fs";
import {
  argbFromHex,
  MaterialDynamicColors as C,
  DynamicScheme,
  Hct,
  hexFromArgb,
  TonalPalette,
} from "@material/material-color-utilities";

// Variant.TONAL_SPOT; the enum is not exported from the package root.
const TONAL_SPOT = 2;

const SEED = { primary: "#0e5561", tertiary: "#f4a27a" };
const GOOD = "#2a7a4b";
const WARN = "#c25f33";

const primary = Hct.fromInt(argbFromHex(SEED.primary));
const palettes = {
  primaryPalette: TonalPalette.fromInt(argbFromHex(SEED.primary)),
  secondaryPalette: TonalPalette.fromHueAndChroma(primary.hue, 16),
  tertiaryPalette: TonalPalette.fromInt(argbFromHex(SEED.tertiary)),
  neutralPalette: TonalPalette.fromHueAndChroma(primary.hue, 4),
  neutralVariantPalette: TonalPalette.fromHueAndChroma(primary.hue, 8),
};

const scheme = (isDark) =>
  new DynamicScheme({
    sourceColorArgb: argbFromHex(SEED.primary),
    variant: TONAL_SPOT,
    contrastLevel: 0,
    isDark,
    ...palettes,
  });

const tone = (hex, t) => hexFromArgb(TonalPalette.fromInt(argbFromHex(hex)).tone(t));

// Our token names, mapped onto M3 roles.
const tokens = (s, dark) => {
  const r = (role) => hexFromArgb(role.getArgb(s));
  return {
    bg: r(C.surface),
    // Cards: white in light; in dark, a step above the page rather than below it.
    surface: r(dark ? C.surfaceContainerLow : C.surfaceContainerLowest),
    "surface-container": r(C.surfaceContainer),
    "surface-container-high": r(C.surfaceContainerHighest),
    text: r(C.onSurface),
    muted: r(C.onSurfaceVariant),
    border: r(C.outlineVariant),
    outline: r(C.outline),
    accent: r(C.primary),
    "on-accent": r(C.onPrimary),
    "primary-container": r(C.primaryContainer),
    "on-primary-container": r(C.onPrimaryContainer),
    tertiary: r(C.tertiary),
    "tertiary-container": r(C.tertiaryContainer),
    "on-tertiary-container": r(C.onTertiaryContainer),
    good: tone(GOOD, dark ? 75 : 45),
    warn: tone(WARN, dark ? 75 : 45),
    "series-base": r(C.outline),
    "series-a": r(C.primary),
    "series-b": tone(WARN, dark ? 70 : 50),
    "series-c": tone("#5a8667", dark ? 75 : 50),
    grid: r(C.surfaceContainerHigh),
  };
};

const block = (t) =>
  Object.entries(t)
    .map(([k, v]) => `  --${k}: ${v};`)
    .join("\n");

const css = `/* Generated by scripts/m3-colors.mjs from ${SEED.primary} (primary) and ${SEED.tertiary} (tertiary). Do not edit by hand. */
:root {
${block(tokens(scheme(false), false))}
}

@media (prefers-color-scheme: dark) {
  :root {
${block(tokens(scheme(true), true)).replace(/^/gm, "  ")}
  }
}
`;
writeFileSync(new URL("../src/app/m3-tokens.css", import.meta.url), css);
console.log(css);
